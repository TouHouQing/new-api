func TestNativeImageEditFixedOutputVersionIgnoresLaterAssetRevision(t *testing.T) {
	s, db, input, _, candidate := nativeImageEditFixture(t)
	task := nativeImageEditTask(t, s, db, input, "")
	name, err := s.stageInlineMedia(candidate)
	if err != nil {
		t.Fatal(err)
	}
	checkpoint := &mediaCheckpoint{Mode: "image", StartedAt: time.Now(), Items: []mediaCheckpointItem{{TempName: name, MIMEType: "image/png"}}}
	if err := s.saveMediaCheckpoint(task, checkpoint, "download"); err != nil {
		t.Fatal(err)
	}
	result, err := s.resumeTaskMedia(context.Background(), task)
	if err != nil {
		t.Fatal(err)
	}
	encoded, _ := json.Marshal(result)
	task.ResultJSON = string(encoded)
	if err := s.registerRecoveredMediaAssets(*task); err != nil {
		t.Fatal(err)
	}
	if err := s.bindTaskMediaAssetVersions(task); err != nil {
		t.Fatal(err)
	}
	var bound map[string]any
	json.Unmarshal([]byte(task.ResultJSON), &bound)
	output := creationMaps(bound["images"])[0]
	versionID := stringValue(output["assetVersionId"])
	assetID, resourceID := stringValue(output["assetId"]), stringValue(output["resourceId"])
	if versionID == "" || assetID != generationMediaAssetID(task.ID, 0) {
		t.Fatal("native output has no fixed registered version", output)
	}
	if err := db.Create(&model.AssetVersion{ID: "later-manual-revision", AssetID: assetID, Version: 2, Status: model.AssetVersionStatusConfirmed, DefinitionJSON: `{}`, CreatedAt: time.Now(), UpdatedAt: time.Now()}).Error; err != nil {
		t.Fatal(err)
	}
	if err := s.bindTaskMediaAssetVersions(task); err != nil {
		t.Fatal(err)
	}
	metadata := map[string]any{"assetVersionId": "stale-from-another-output"}
	applyTaskMediaAssetVersion(metadata, task, resourceID, assetID)
	if metadata["assetVersionId"] != versionID {
		t.Fatal("later asset revision replaced the task's fixed version", metadata)
	}
	applyTaskMediaAssetVersion(metadata, task, "unrelated-resource", assetID)
	if metadata["assetVersionId"] != nil {
		t.Fatal("another resource inherited a stale fixed version", metadata)
	}
}

