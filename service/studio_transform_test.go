func TestStudioRegionReworkPreservesEveryPixelOutsideTheSelectedRectangle(t *testing.T) {
	studioProductionFixture(t)
	source := image.NewRGBA(image.Rect(0, 0, 8, 6))
	for y := range 6 {
		for x := range 8 {
			source.SetRGBA(x, y, color.RGBA{uint8(x * 20), uint8(y * 25), 15, 255})
		}
	}
	var original bytes.Buffer
	require.NoError(t, png.Encode(&original, source))
	_, err := SaveStudioMedia(1, "region-source", "image/png", &original)
	require.NoError(t, err)
	patch := image.NewRGBA(image.Rect(0, 0, 2, 2))
	for y := range 2 {
		for x := range 2 {
			patch.SetRGBA(x, y, color.RGBA{0, 0, 255, 255})
		}
	}
	var generated bytes.Buffer
	require.NoError(t, png.Encode(&generated, patch))
	data := map[string]any{"reworkRegion": map[string]any{"sourceMediaId": "region-source", "x": 2, "y": 1, "width": 3, "height": 2}}
	output, mime, err := studioComposeImageRegion(1, data, generated.Bytes())
	require.NoError(t, err)
	assert.Equal(t, "image/png", mime)
	decoded, _, err := image.Decode(bytes.NewReader(output))
	require.NoError(t, err)
	assert.Equal(t, source.Bounds(), decoded.Bounds())
	for y := range 6 {
		for x := range 8 {
			if x >= 2 && x < 5 && y >= 1 && y < 3 {
				assert.Equal(t, color.RGBA{0, 0, 255, 255}, color.RGBAModel.Convert(decoded.At(x, y)))
			} else {
				assert.Equal(t, source.At(x, y), color.RGBAModel.Convert(decoded.At(x, y)))
			}
		}
	}
	_, _, err = studioComposeImageRegion(2, data, generated.Bytes())
	assert.Error(t, err)
	data["reworkRegion"].(map[string]any)["width"] = 9
	_, _, err = studioComposeImageRegion(1, data, generated.Bytes())
	assert.Error(t, err)
}

func TestStudioRegionReworkBlendsOnlyInsideTheBoundaryAndKeepsTheEditedCenter(t *testing.T) {
	studioProductionFixture(t)
	source := image.NewRGBA(image.Rect(0, 0, 64, 64))
	draw.Draw(source, source.Bounds(), image.NewUniform(color.RGBA{240, 220, 200, 255}), image.Point{}, draw.Src)
	var original bytes.Buffer
	require.NoError(t, png.Encode(&original, source))
	_, err := SaveStudioMedia(1, "feather-source", "image/png", &original)
	require.NoError(t, err)
	var generated bytes.Buffer
	patch := image.NewRGBA(image.Rect(0, 0, 16, 16))
	draw.Draw(patch, patch.Bounds(), image.NewUniform(color.RGBA{0, 0, 255, 255}), image.Point{}, draw.Src)
	require.NoError(t, png.Encode(&generated, patch))
	data := map[string]any{"reworkRegion": map[string]any{"sourceMediaId": "feather-source", "x": 16, "y": 16, "width": 32, "height": 32}}
	output, _, err := studioComposeImageRegion(1, data, generated.Bytes())
	require.NoError(t, err)
	decoded, _, err := image.Decode(bytes.NewReader(output))
	require.NoError(t, err)
	assert.Equal(t, source.At(16, 32), color.RGBAModel.Convert(decoded.At(16, 32)), "the seam starts with the original boundary pixel")
	near := color.RGBAModel.Convert(decoded.At(17, 32)).(color.RGBA)
	assert.Greater(t, near.R, uint8(0), "the boundary must blend instead of pasting a hard rectangle")
	assert.Less(t, near.R, uint8(240))
	assert.Equal(t, color.RGBA{0, 0, 255, 255}, color.RGBAModel.Convert(decoded.At(32, 32)), "the center retains the generated edit")
	for y := range 64 {
		for x := range 64 {
			if !image.Pt(x, y).In(image.Rect(16, 16, 48, 48)) {
				assert.Equal(t, source.At(x, y), color.RGBAModel.Convert(decoded.At(x, y)))
			}
		}
	}
}

