func TestStudioNativeCropRetainsSourceAndPublishesEditableResult(t *testing.T) {
	if !StudioRenderAvailable() {
		t.Skip("FFmpeg is not configured")
	}
	studioProductionFixture(t)
	StudioWorkflowRelay = func(context.Context, *model.StudioWorkflowJob, string, []byte) (StudioRelayResponse, error) {
		t.Fatal("native edits must not call a model")
		return StudioRelayResponse{}, nil
	}
	var source bytes.Buffer
	require.NoError(t, png.Encode(&source, image.NewRGBA(image.Rect(0, 0, 80, 60))))
	original := append([]byte(nil), source.Bytes()...)
	_, err := SaveStudioMedia(1, "source-image", "image/png", &source)
	require.NoError(t, err)
	document := `{"id":"film","title":"Film","nodes":[{"id":"source","data":{"kind":"image","prompt":"","mediaId":"source-image"}},{"id":"target","data":{"kind":"image","title":"Crop","prompt":"","sourceMode":"upload"}}],"edges":[]}`
	var complete map[string]any
	require.NoError(t, common.Unmarshal([]byte(document), &complete))
	studioCompleteTestDocument(t, complete)
	raw, err := common.Marshal(complete)
	require.NoError(t, err)
	project, err := model.SaveStudioProject(1, "film", "Film", 0, string(raw))
	require.NoError(t, err)
	operation := &StudioMediaOperation{Action: "crop", NodeID: "target", MediaID: "source-image", Edit: &StudioMediaEdit{X: 10, Y: 5, Width: 30, Height: 20}}
	job, err := QueueStudioWorkflow(1, "film", "crop-one", "transform", project.Revision, 0, nil, nil, operation)
	require.NoError(t, err)
	RunStudioWorkflowsOnce(context.Background(), "crop-worker")
	require.NoError(t, model.DB.First(job, "id = ?", job.ID).Error)
	require.Equal(t, "succeeded", job.Status, job.Error)
	var progress StudioWorkflowProgress
	require.NoError(t, common.Unmarshal([]byte(job.Result), &progress))
	media, err := GetStudioMedia(1, progress.Take["mediaId"].(string))
	require.NoError(t, err)
	path, err := StudioMediaPath(media)
	require.NoError(t, err)
	file, err := os.Open(path)
	require.NoError(t, err)
	defer file.Close()
	output, err := png.DecodeConfig(file)
	require.NoError(t, err)
	assert.Equal(t, 30, output.Width)
	assert.Equal(t, 20, output.Height)
	retained, err := GetStudioMedia(1, "source-image")
	require.NoError(t, err)
	retainedPath, err := StudioMediaPath(retained)
	require.NoError(t, err)
	data, err := os.ReadFile(retainedPath)
	require.NoError(t, err)
	assert.Equal(t, original, data)
	again, err := QueueStudioWorkflow(1, "film", "crop-one", "transform", project.Revision, 0, nil, nil, operation)
	require.NoError(t, err)
	assert.Equal(t, job.ID, again.ID)
}

